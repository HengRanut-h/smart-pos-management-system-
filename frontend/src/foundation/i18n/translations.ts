/**
 * Format currency with locale awareness
 */
export const formatCurrency = (
  amount: number,
  currency: 'USD' | 'KHR' = 'USD',
  lang: Language = 'en'
): string => {
  const isKh = lang === 'kh' || lang === 'km';
  if (currency === 'KHR') {
    const formatted = new Intl.NumberFormat(isKh ? 'km-KH' : 'en-US', {
      maximumFractionDigits: 0,
    }).format(amount);
    return isKh ? `${formatted} ៛` : `${formatted} KHR`;
  }

  const formatted = new Intl.NumberFormat(isKh ? 'km-KH' : 'en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(amount);
  return `$${formatted}`;
};

/**
 * Format date with locale awareness
 */
export const formatDate = (
  date: string | Date | number,
  lang: Language = 'en',
  options?: Intl.DateTimeFormatOptions
): string => {
  const isKh = lang === 'kh' || lang === 'km';
  const d = new Date(date);
  if (isNaN(d.getTime())) return '';

  const defaultOptions: Intl.DateTimeFormatOptions = options || {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  };

  return d.toLocaleDateString(isKh ? 'km-KH' : 'en-US', defaultOptions);
};

/**
 * Format number with locale awareness
 */
export const formatNumber = (num: number, lang: Language = 'en'): string => {
  const isKh = lang === 'kh' || lang === 'km';
  return new Intl.NumberFormat(isKh ? 'km-KH' : 'en-US').format(num);
};

